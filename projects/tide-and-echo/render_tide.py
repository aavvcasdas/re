def draw_clawd(c: Painter, pose: dict, t: float, p: float, info: dict) -> tuple[float,float]:
    """Clawd: terracotta block, two slit eyes, two arm nubs and four stubby feet."""
    x,y,s,tilt=pose["x"],pose["y"],pose["scale"]*1.15,pose["tilt"]
    run=pose["run"]
    bob=5*math.sin(t*3.3)+run*7*abs(math.sin(t*8))
    y+=bob
    squash=0.025*math.sin(t*5.5)+0.03*run*math.sin(t*8+0.5)
    sx=s*(1+squash);sy=s*(1-squash)
    co,si=math.cos(tilt),math.sin(tilt)
    def xf(px:float,py:float)->tuple[float,float]:
        lx,ly=px*sx,py*sy
        return x+lx*co-ly*si,y+lx*si+ly*co
    def shape(points,fill,alpha=255,outline=INK,line=2.0,soft=0.5,key=0,jitter=0.7):
        c.polygon([xf(a,b) for a,b in points],fill,alpha,outline,line,soft,jitter,key)
