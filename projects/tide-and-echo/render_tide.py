    ellipse(-30,-204,41,13,CLAY_LIGHT,72,None,0,651)
    shape([(-84,-199),(-72,-211),(-73,-104),(-85,-91)],CLAY_DARK,38,None,0,2.4,652,0.4)
    # Scarf knot and the loose end flutter according to the tide.
    scarf_y=-105
    shape([(-36,scarf_y-6),(37,scarf_y-4),(30,scarf_y+11),(-32,scarf_y+13)],TEAL,242,INK,1.2,0.5,653,0.5)
    flutter=11*math.sin(t*3.4)
    shape([(28,scarf_y+6),(64,scarf_y+15+flutter),(53,scarf_y+30+flutter),(24,scarf_y+15)],
          "#54858D",228,INK,1.0,0.4,654,0.5)
    line([(-67,-218),(-42,-220),(-17,-216)],CLAY_LIGHT,1.2,135,655)
    # Acting expressions; no facial captions or spoken text.
    expr=pose["expression"]
    blink=math.sin(t*1.45+0.4)>0.988
    for side in (-1,1):
        ex=side*34
        if expr in ("wide","startled","search","reaching"):
            ellipse(ex,-188,9.8,14,CREAM,255,INK,1.6,660+side)
            ellipse(ex+pose["look"]*3,-188,4.3,7.5,INK,255,None,0,670+side)
            ellipse(ex-1,-192,1.8,2.5,CREAM,230,None,0,680+side)
        elif expr in ("sad","hurt","remember","wistful","moon") and side==1:
            line([(ex-10,-190),(ex-3,-185),(ex+5,-187),(ex+10,-193)],INK,3.1,255,690+side)
        elif blink or expr in ("soft","peace"):
            line([(ex-10,-189),(ex-5,-194),(ex+4,-194),(ex+10,-188)],INK,3.5,255,700+side)
        else:
            ellipse(ex,-188,7.4,15,INK,255,None,0,710+side)
            ellipse(ex-2,-194,1.8,3,CREAM,230,None,0,720+side)
