// bundle_fonts.mjs — build assets/fonts/ from the installed @fontsource packages,
// keeping only the font subsets that the project's text actually needs.
//
// Why: an offline render cannot reach fonts.googleapis.com, and the CJK packages are
// 14–87 MB because they ship ~100–800 unicode-range subsets. A lyric video uses a few
// hundred distinct characters, so we copy only the subsets that cover `assets/lyrics.txt`
// plus the Latin UI faces, and emit a self-contained fonts.css.
//
//   node tools/bundle_fonts.mjs [--all]
//
// --all copies every subset (bigger, but renders any future text).
import { readFileSync, writeFileSync, mkdirSync, copyFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'assets/fonts');
const ALL = process.argv.includes('--all');

const text = readFileSync(join(ROOT, 'assets/lyrics.txt'), 'utf8');
const LYRICS = [...text].filter(c => !/\s/.test(c));
// Latin strings the studio chrome / sheets / scene labels may draw.
const LABELS = [...'0123456789:.,-—·、。！？…()[]%×ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz'];

// [family, package, css file, characters this face must cover]
const FONTS = [
  ['Ma Shan Zheng', 'ma-shan-zheng', 'chinese-simplified-400.css', LYRICS],
  ['Ma Shan Zheng', 'ma-shan-zheng', 'latin-400.css', LYRICS],
  ['Permanent Marker', 'permanent-marker', '400.css', LABELS],
  ['Shantell Sans', 'shantell-sans', '800.css', LABELS],
];

/** @font-face blocks in a fontsource CSS file. */
function parseBlocks(css) {
  const out = [];
  for (const m of css.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
    const body = m[1];
    const field = k => (body.match(new RegExp(`(?:^|;|\\s)${k}\\s*:\\s*([^;]+);`)) || [])[1]?.trim();
    const url = body.match(/url\(\s*['"]?([^'")]+)['"]?\s*\)/);
    const range = field('unicode-range');
    out.push({
      family: (field('font-family') || '').replace(/['"]/g, ''),
      style: field('font-style') || 'normal',
      weight: field('font-weight') || '400',
      file: url ? url[1].trim() : null,
      ranges: range ? range.split(',').map(r => r.trim()).filter(Boolean) : null,
    });
  }
  return out;
}

function coveredBy(ranges, ch) {
  if (!ranges) return true; // no unicode-range → the whole face
  const cp = ch.codePointAt(0);
  return ranges.some(r => {
    const p = r.replace(/^U\+/i, '');
    if (!p) return false;
    const [a, b] = p.split('-');
    const lo = parseInt(a, 16), hi = b ? parseInt(b, 16) : lo;
    return cp >= lo && cp <= hi;
  });
}

mkdirSync(OUT, { recursive: true });
const cssOut = ['/* generated by tools/bundle_fonts.mjs — do not edit by hand */'];
let copied = 0, skipped = 0, bytes = 0;

for (const [family, pkg, cssFile, wanted] of FONTS) {
  const dir = join(ROOT, 'node_modules', '@fontsource', pkg);
  const cssPath = join(dir, cssFile);
  if (!existsSync(cssPath)) { console.log(`  skip ${family} (${cssFile}): not installed`); continue; }
  const destDir = join(OUT, pkg);
  mkdirSync(destDir, { recursive: true });

  for (const b of parseBlocks(readFileSync(cssPath, 'utf8'))) {
    if (!b.file) continue;
    const keep = ALL || wanted.some(ch => coveredBy(b.ranges, ch));
    if (!keep) { skipped++; continue; }
    const src = join(dir, b.file);
    if (!existsSync(src)) continue;
    const name = b.file.split('/').pop();
    const dest = join(destDir, name);
    if (!existsSync(dest)) { copyFileSync(src, dest); bytes += statSync(dest).size; }
    copied++;
    cssOut.push(
      `@font-face { font-family: '${b.family}'; font-style: ${b.style}; font-weight: ${b.weight}; ` +
      `font-display: block; src: url('./${pkg}/${name}') format('woff2');` +
      (b.ranges ? ` unicode-range: ${b.ranges.join(', ')};` : '') + ' }'
    );
  }
  // report any lyric character this family cannot set
  const uncovered = wanted.filter(ch => !parseBlocks(readFileSync(cssPath, 'utf8')).some(b => coveredBy(b.ranges, ch)));
  if (uncovered.length) console.log(`  ${family} ${cssFile}: uncovered → ${[...new Set(uncovered)].join('')}`);
}

writeFileSync(join(OUT, 'fonts.css'), cssOut.join('\n') + '\n');
console.log(`  kept ${copied} faces, dropped ${skipped} → assets/fonts (${(bytes / 1048576).toFixed(2)} MB, ${cssOut.length - 1} rules)`);
